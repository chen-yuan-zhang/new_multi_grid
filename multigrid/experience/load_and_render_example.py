def example_5_compare_behaviors():
    """Example 5: Compare different behavior styles on same layout."""
    print("\n" + "="*60)
    print("EXAMPLE 5: Comparing Behavior Styles")
    print("="*60)
    
    # Load dataset
    results = load_dataset('results.pkl.gz')
    
    # Find scenarios with same layout but different styles
    # Group by (size, layout_id, scenario_id)
    from collections import defaultdict
    grouped = defaultdict(list)
    
    for scenario in results:
        key = (scenario['size'], scenario['layout_id'], scenario['scenario_id'])
        grouped[key].append(scenario)
    
    # Find a group with all 4 styles
    for key, scenarios in grouped.items():
        if len(scenarios) == 4:
            print(f"\nFound complete set: Size={key[0]}, Layout={key[1]}, Scenario={key[2]}")
            
            # Create comparison plot
            fig, axes = plt.subplots(2, 2, figsize=(16, 16))
            axes = axes.flatten()
            
            style_names = ["like_wall", "hate_wall", "like_edge", "hate_edge"]
            
            for i, scenario in enumerate(sorted(scenarios, key=lambda s: s['hidden_cost_type'])):
                ax = axes[i]
                
                # Plot base grid
                grid = scenario['base_grid']
                ax.imshow(grid.T, cmap='gray_r', origin='lower', alpha=0.3)
                
                # Plot goals
                for goal in scenario['goals']:
                    color = 'red' if goal == scenario['goal'] else 'blue'
                    marker = '*' if goal == scenario['goal'] else 'o'
                    ax.plot(goal[0], goal[1], marker=marker, markersize=15, color=color)
                
                # Plot trajectory
                positions = [obs['target_pos'] for obs in scenario['all_obs']]
                positions = [(scenario['start_positions'][0], scenario['start_positions'][1])] + positions
                
                x_coords = [pos[0] for pos in positions]
                y_coords = [pos[1] for pos in positions]
                
                ax.plot(x_coords, y_coords, 'g-', linewidth=2, alpha=0.7)
                ax.plot(x_coords[0], y_coords[0], 'go', markersize=12)
                
                ax.set_xlim(-0.5, scenario['size'] - 0.5)
                ax.set_ylim(-0.5, scenario['size'] - 0.5)
                ax.set_title(f"{style_names[scenario['hidden_cost_type']]} ({len(scenario['all_actions'])} steps)")
                ax.grid(True, alpha=0.3)
            
            plt.tight_layout()
            plt.savefig('behavior_comparison.png', dpi=150, bbox_inches='tight')
            print("✅ Behavior comparison saved to behavior_comparison.png")
            plt.close()
            break


